"""Read-only installed-state probe for one private synthetic S3 task."""

from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import importlib
import importlib.util
import io
import json
import os
import re
import sys
import sysconfig
from importlib.machinery import PathFinder
from importlib.metadata import Distribution, distributions
from pathlib import Path

VERSIONS = ("2.0.0", "2.1.0a4", "2.1.0rc1")
FIXTURE = b"- S3 synthetic parent\n\t- S3 synthetic child\n"
MAX_RECORD = 8 * 1024 * 1024
MAX_FILE = 64 * 1024 * 1024
MAX_TOTAL = 128 * 1024 * 1024
INSTALLER_METADATA = frozenset(
    {"INSTALLER", "direct_url.json", "REQUESTED", "uv_cache.json", "uv_build.json"}
)


class ProbeError(ValueError):
    """Error with a fixed, safe-to-report probe message."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ProbeError(message)


def owned_path(path: Path, root: Path) -> Path:
    """Reject escapes and symlinks, including nested components under the root."""
    normalized = Path(os.path.abspath(path))
    require(normalized.is_relative_to(root), "Path is outside its owned root.")
    require(normalized.resolve(strict=True) == normalized, "Owned path crosses a symlink.")
    return normalized


def unique_distribution(site: Path, name: str) -> Distribution:
    matches = [dist for dist in distributions(path=[str(site)], name=name)]
    require(len(matches) == 1, "Expected exactly one matching installed distribution.")
    return matches[0]


def verify_record(site: Path, prefix: Path, dist_name: str) -> tuple[set[Path], str]:
    name = dist_name.replace("-", "_")
    directories = list(site.glob(f"{name}-*.dist-info"))
    require(len(directories) == 1, "Expected exactly one matching metadata directory.")
    record = owned_path(directories[0] / "RECORD", prefix)
    require(record.is_file() and 0 < record.stat().st_size <= MAX_RECORD, "Invalid RECORD file.")
    with record.open("rb") as stream:
        raw = stream.read(MAX_RECORD + 1)
    require(0 < len(raw) <= MAX_RECORD, "Invalid RECORD read size.")
    rows = list(csv.reader(io.StringIO(raw.decode("utf-8"), newline=""), strict=True))
    require(0 < len(rows) <= 20_000, "Invalid RECORD row count.")
    seen: set[Path] = set()
    verified: set[Path] = set()
    total = 0
    for row in rows:
        require(len(row) == 3, "Invalid RECORD row.")
        name, digest, size = row
        require(
            bool(name) and not name.startswith("/") and "\\" not in name and "\0" not in name,
            "Invalid RECORD path.",
        )
        path = owned_path(site / name, prefix)
        require(path.is_file() and path not in seen, "Invalid or duplicate RECORD file.")
        require(
            name == os.path.relpath(path, site)
            and (path.is_relative_to(site) or path.parent == prefix / "bin"),
            "RECORD path must name installed payload or an owned launcher.",
        )
        seen.add(path)
        if not digest and not size:
            # Allow only RECORD, generated bytecode and installer-generated metadata.
            require(
                path == record
                or (path.suffix == ".pyc" and path.parent.name == "__pycache__")
                or (path.parent == record.parent and path.name in INSTALLER_METADATA),
                "Unsigned installed payload is not permitted.",
            )
            continue
        require(
            path != record and re.fullmatch(r"sha256=[A-Za-z0-9_-]{43}", digest) is not None,
            "Invalid RECORD digest.",
        )
        length = path.stat().st_size
        total += length
        require(
            str(length) == size and length <= MAX_FILE and total <= MAX_TOTAL,
            "Invalid RECORD file size.",
        )
        with path.open("rb") as stream:
            sha256 = hashlib.file_digest(stream, "sha256").digest()
        actual = base64.urlsafe_b64encode(sha256).decode("ascii").rstrip("=")
        require(digest == f"sha256={actual}", "RECORD digest differs from installed payload.")
        verified.add(path)
    require(record in seen and bool(verified), "RECORD is incomplete.")
    require(record.with_name("METADATA") in verified, "RECORD does not authenticate METADATA.")
    return verified, hashlib.sha256(raw).hexdigest()


def check_module(name: str, initial_path: Path, verified: set[Path]) -> Path:
    """Resolve package and module origins without importing any package parents."""
    search_path = [str(initial_path)]
    qualified: list[str] = []
    for part in name.split("."):
        qualified.append(part)
        spec = PathFinder.find_spec(".".join(qualified), search_path)
        if spec is None or not spec.origin:
            raise ProbeError("An installed module spec has no file origin.")
        origin = Path(spec.origin)
        require(origin in verified, "Module origin is not hashed installed payload.")
        search_path = list(spec.submodule_search_locations or ())
    return origin


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expected-version", choices=VERSIONS, required=True)
    parser.add_argument("--prefix", type=Path, required=True)
    parser.add_argument("--fixture", type=Path, required=True)
    args = parser.parse_args()
    try:
        require(bool(sys.flags.isolated and sys.dont_write_bytecode), "Use venv Python -I -B.")
        cwd = Path.cwd()
        require(cwd.resolve(strict=True) == cwd, "Probe working directory must be canonical.")
        prefix = owned_path(args.prefix, cwd)
        require(prefix.parent == cwd and Path(sys.prefix) == prefix, "Incorrect installed prefix.")
        require(sys.prefix != sys.base_prefix, "Interpreter must be in an isolated venv.")
        require(not cwd.is_relative_to(prefix), "Use a separate owned probe cwd.")
        # -B disables writes, but does not disable reads of existing bytecode.
        bytecode_root = cwd / ".unused-s3-probe-bytecode"
        require(not os.path.lexists(bytecode_root), "Probe bytecode path must be absent.")
        sys.pycache_prefix = str(bytecode_root)
        fixture = owned_path(args.fixture, cwd)
        require(
            fixture.suffix == ".md"
            and fixture.is_file()
            and fixture.stat().st_size == len(FIXTURE),
            "Invalid synthetic fixture file.",
        )
        require(fixture.read_bytes() == FIXTURE, "Fixture is not the exact synthetic page.")
        site = owned_path(Path(sysconfig.get_path("purelib")), prefix)
        require(str(site) in sys.path, "Installed site-packages is not on the interpreter path.")

        plumber_files, plumber_record = verify_record(site, prefix, "matryca-plumber")
        parser_files, parser_record = verify_record(site, prefix, "logseq-matryca-parser")
        plumber = unique_distribution(site, "matryca-plumber")
        parser_dist = unique_distribution(site, "logseq-matryca-parser")
        require(
            plumber.version == args.expected_version, "Installed Plumber version does not match."
        )

        module_name = "src.rag.matryca_hooks"
        parser_name = "logseq_matryca_parser"
        require(
            not any(name in sys.modules for name in ("src", "src.rag", module_name, parser_name)),
            "Probe modules were imported before origin verification.",
        )
        plumber_origin = check_module(module_name, site, plumber_files)
        parser_origin = check_module(parser_name, site, parser_files)
        for top in ("src", parser_name):
            actual_spec = importlib.util.find_spec(top)
            expected_origin = check_module(
                top, site, plumber_files if top == "src" else parser_files
            )
            require(
                actual_spec is not None and actual_spec.origin == str(expected_origin),
                "Active import path does not identify the selected venv.",
            )
        module = importlib.import_module(module_name)
        parser_module = importlib.import_module(parser_name)
        require(
            module.__file__ == str(plumber_origin) and parser_module.__file__ == str(parser_origin),
            "Imported package origin changed after verification.",
        )
        page = module.get_spatial_context(str(fixture))
        roots = page.root_nodes
        require(len(roots) == 1 and len(roots[0].children) == 1, "Nested parse structure differs.")
        parent, child = roots[0], roots[0].children[0]
        require(
            parent.clean_text.strip() == "S3 synthetic parent"
            and child.clean_text.strip() == "S3 synthetic child"
            and not child.children,
            "Nested parse content differs.",
        )
        require(fixture.read_bytes() == FIXTURE, "Synthetic fixture bytes changed.")
        require(not os.path.lexists(bytecode_root), "Probe unexpectedly created bytecode.")
        print(
            json.dumps(
                {
                    "status": "PASS",
                    "plumber_version": plumber.version,
                    "parser_version": parser_dist.version,
                    "plumber_record_sha256": plumber_record,
                    "parser_record_sha256": parser_record,
                    "fixture_sha256": hashlib.sha256(FIXTURE).hexdigest(),
                    "nested_read": True,
                },
                sort_keys=True,
            )
        )
        return 0
    except ProbeError as exc:
        print(f"Installed probe failed: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:
        print(f"Installed probe failed: {type(exc).__name__}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
